<script>
  (function() {
    const modal = document.getElementById('arGameModal');
    const openBtn = document.getElementById('openArGame');
    const closeBtn = document.getElementById('closeArGame');
    const progress = document.getElementById('miniProgress');
    const winArea = document.getElementById('miniGameWin');
    const items = document.querySelectorAll('.mini-item');
    const foundItems = new Set();

    function openModal() {
      modal.classList.remove('hidden');
      modal.classList.add('flex');
      document.body.style.overflow = 'hidden';
    }

    function closeModal() {
      modal.classList.add('hidden');
      modal.classList.remove('flex');
      document.body.style.overflow = '';
    }

    openBtn?.addEventListener('click', openModal);
    closeBtn?.addEventListener('click', closeModal);
    modal?.addEventListener('click', (e) => { if (e.target === modal) closeModal(); });

    items.forEach(item => {
      item.addEventListener('click', () => {
        if (item.classList.contains('found')) return;
        item.classList.add('found');
        foundItems.add(item.dataset.item);
        progress.textContent = foundItems.size + '/3 nhạc cụ';
        if (foundItems.size >= 3) {
          localStorage.setItem('hasVoucher', 'true');
          localStorage.setItem('hatXoanDiscount', '20');
          setTimeout(() => { winArea.classList.remove('hidden'); }, 400);
        }
      });
    });
  })();
</script>

